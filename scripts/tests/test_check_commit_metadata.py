import importlib.util
from pathlib import Path
import unittest


spec = importlib.util.spec_from_file_location(
    "check_commit_metadata", Path(__file__).parents[1] / "check-commit-metadata.py"
)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
findings = module.findings


class CheckCommitMetadataTests(unittest.TestCase):
    def assert_rule(self, text, rule):
        self.assertEqual([found_rule for found_rule, _ in findings(text)], [rule])

    def test_session_trailer(self):
        self.assert_rule(
            "fix: thing\n\nClaude-Session: https://example.test/s/1", "session trailer"
        )

    def test_session_link_in_body(self):
        self.assert_rule("Summary.\n\nhttps://claude.ai/code/session_01ABC", "session link")

    def test_co_author_trailer(self):
        self.assert_rule(
            "fix\n\nCo-authored-by: Claude <noreply@anthropic.com>", "co-author trailer"
        )

    def test_generated_footer(self):
        self.assert_rule("🤖 Generated with [Claude Code](https://example.test)", "generated-by footer")

    def test_one_finding_per_line(self):
        self.assertEqual(len(findings("Generated by [Claude Code](https://claude.ai/code)")), 1)

    def test_clean_text_passes(self):
        text = (
            "fix(worker): flush a full batch\n\n"
            "Co-authored-by: Jane Doe <jane@example.com>\n"
            "See https://docs.coderabbit.ai/guides/configuration and AGENTS.md.\n"
            "The session trailer was removed."
        )
        self.assertEqual(findings(text), [])


if __name__ == "__main__":
    unittest.main()
